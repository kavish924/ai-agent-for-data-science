"""Build the corrupted benchmark (Spec 10 NFR-16).

Usage (from backend/):
    python -m eval.build_benchmark --samples --seeds 1 2 3          # samples/ + eval/golden.json
    python -m eval.build_benchmark --manifest --seeds 1 2 3         # fetched OpenML data
    python -m eval.build_benchmark --samples --manifest --out eval/benchmark/build

Writes `<stem>__s<seed>.csv` and one `golden.json` into --out (default
eval/benchmark/build, gitignored). Then score it with
    python -m eval.run --golden eval/benchmark/build/golden.json
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import pandas as pd

from . import corrupt, fetch_datasets, harness

OUT_DIR = harness.EVAL_DIR / "benchmark" / "build"
_DOC = ("Generated by eval/build_benchmark.py (Spec 10 NFR-16): seeded corruptions with exact ground "
        "truth. Matching rules as in eval/golden.json. Regenerate instead of editing.")


@dataclass(frozen=True)
class Source:
    path: Path
    target: str
    golden: dict[str, Any] | None = None


def build(sources: list[Source], seeds: list[int], out_dir: Path) -> dict[str, dict[str, Any]]:
    out_dir.mkdir(parents=True, exist_ok=True)
    datasets: dict[str, dict[str, Any]] = {}
    for src in sources:
        df = pd.read_csv(src.path)
        for seed in seeds:
            protected = corrupt.protected_columns(src.golden) if src.golden else []
            frame, entry = corrupt.corrupt(df, src.target, seed, protected)
            if src.golden:
                entry = corrupt.merge_golden(src.golden, entry)
            name = f"{src.path.stem}__s{seed}.csv"
            data = frame.to_csv(index=False, lineterminator="\n").encode("utf-8")
            (out_dir / name).write_bytes(data)
            datasets[name] = {"source": src.path.name, "seed": seed, **entry,
                              "sha256": hashlib.sha256(data).hexdigest()}
    text = json.dumps({"_doc": _DOC, "datasets": datasets}, ensure_ascii=False, indent=1)
    (out_dir / "golden.json").write_text(text + "\n", encoding="utf-8")
    return datasets


def sample_sources() -> list[Source]:
    golden = harness.load_golden()
    return [Source(path=harness.SAMPLES / name, target=g["target"], golden=g) for name, g in golden.items()]


def manifest_sources(data_dir: Path = fetch_datasets.DATA_DIR) -> list[Source]:
    out = []
    for e in fetch_datasets.load_manifest():
        path = data_dir / f"{e['name']}.csv"
        if path.exists():
            out.append(Source(path=path, target=e["target"]))
        else:
            print(f"[skip] {e['name']}: not fetched (run python -m eval.fetch_datasets)")
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--samples", action="store_true", help="corrupt samples/ (with their golden entries)")
    parser.add_argument("--manifest", action="store_true", help="corrupt the fetched manifest datasets")
    parser.add_argument("--seeds", type=int, nargs="+", default=[1, 2, 3])
    parser.add_argument("--out", type=Path, default=OUT_DIR)
    args = parser.parse_args(argv)
    sources = (sample_sources() if args.samples else []) + (manifest_sources() if args.manifest else [])
    if not sources:
        print("nothing to build: pass --samples and/or --manifest")
        return 2
    datasets = build(sources, args.seeds, args.out)
    for name, entry in datasets.items():
        kinds = ", ".join(i["type"] for i in entry["injections"])
        print(f"[ok] {name}: {kinds}" + (f" (skipped {entry['skipped']})" if entry["skipped"] else ""))
    print(f"wrote {len(datasets)} datasets and golden.json to {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
